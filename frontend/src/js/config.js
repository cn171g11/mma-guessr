function renderVersion() {
    document.title = `🌍 MmaGuessr ${VERSION} · 街景猜位置游戏 (OSM + Mapillary)`;
    const text = `版本 ${VERSION}`;
    const hv = $('home-version'),
        vl = $('version-line');
    if (hv) hv.textContent = text;
    if (vl) vl.textContent = text;

    // 题库总数 & 各区数量（仅公示统计，不暴露题目内容）
    const total = LOCATIONS.length;
    const bc = $('bank-count');
    if (bc) bc.textContent = `📚 题库共 ${total} 题`;
    ['asia', 'europe', 'northamerica', 'southamerica', 'africa', 'oceania'].forEach((r) => {
        const el = $('rc-' + r);
        if (el) el.textContent = LOCATIONS.filter((l) => l.region === r).length + ' 题';
    });
}

